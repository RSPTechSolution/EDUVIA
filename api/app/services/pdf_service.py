BRAND = colors.HexColor("#15233F")  # Vidyanexa Ink Navy
GOLD = colors.HexColor("#B8893C")
MUTED = colors.HexColor("#64748b")
LINE = colors.HexColor("#E6DECD")
SOFT = colors.HexColor("#FBF8F2")

_ss = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=_ss["Title"], fontSize=18, leading=22, textColor=BRAND, spaceAfter=2)
SUB = ParagraphStyle("sub", parent=_ss["Normal"], fontSize=9, leading=12, textColor=MUTED, alignment=TA_CENTER)
H2 = ParagraphStyle("h2", parent=_ss["Heading2"], fontSize=13, leading=16, alignment=TA_CENTER, spaceBefore=6, spaceAfter=6)
BODY = ParagraphStyle("body", parent=_ss["Normal"], fontSize=10, leading=14)
SMALL = ParagraphStyle("small", parent=BODY, fontSize=8.5, leading=11, textColor=MUTED)
RIGHT = ParagraphStyle("right", parent=BODY, alignment=TA_RIGHT)


def money(v) -> str:
    return f"Rs. {Decimal(v):,.2f}"


def _esc(s) -> str:
    return (str(s) if s is not None else "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _header(school_name: str, address: str | None, phone: str | None = None) -> list:
    bits = [b for b in (address, f"Phone {phone}" if phone else None) if b]
    return [Paragraph(_esc(school_name), H1), Paragraph(_esc(" · ".join(bits)), SUB) if bits else Spacer(1, 1), Spacer(1, 4)]


def _grid(rows, widths, *, header=True, zebra=True) -> Table:
    t = Table(rows, colWidths=widths, repeatRows=1 if header else 0)
    style = [("FONT", (0, 0), (-1, -1), "Helvetica", 9.5), ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
             ("LINEBELOW", (0, 0), (-1, -1), 0.5, LINE), ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5)]
    if header:
        style += [("BACKGROUND", (0, 0), (-1, 0), BRAND), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                  ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 9.5)]
        if zebra:
            style += [("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, SOFT])]
    t.setStyle(TableStyle(style))
    return t


def _facts(pairs: list[tuple[str, str]], width: float) -> Table:
    """Two columns of label: value pairs."""
    cells = [[Paragraph(f"<font color='#64748b'>{_esc(k)}</font><br/><b>{_esc(v)}</b>", BODY) for k, v in pairs[i:i + 2]]
             for i in range(0, len(pairs), 2)]
    for row in cells:
        while len(row) < 2:
            row.append("")
    t = Table(cells, colWidths=[width / 2] * 2)
    t.setStyle(TableStyle([("BOX", (0, 0), (-1, -1), 0.5, LINE), ("INNERGRID", (0, 0), (-1, -1), 0.5, LINE),
                           ("TOPPADDING", (0, 0), (-1, -1), 6), ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
    return t


def _signatures(labels: list[str]) -> Table:
    """Separate signature lines with a gap between them."""
    gap = 10 * mm
    w = (WIDTH - gap * (len(labels) - 1)) / len(labels)
    cells, widths = [], []
    for i, label in enumerate(labels):
        if i:
            cells.append("")
            widths.append(gap)
        cells.append(label)
        widths.append(w)
    t = Table([cells], colWidths=widths)
    style = [("ALIGN", (0, 0), (-1, -1), "CENTER"), ("FONT", (0, 0), (-1, -1), "Helvetica", 9.5)]
    style += [("LINEABOVE", (c, 0), (c, 0), 0.6, colors.black) for c in range(0, len(cells), 2)]
    t.setStyle(TableStyle(style))
    return t


def build(story: list, title: str) -> bytes:
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=16 * mm, rightMargin=16 * mm, topMargin=14 * mm, bottomMargin=14 * mm,
                            title=title, author="Vidyanexa")

    def footer(canvas, d):
        canvas.saveState()
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(MUTED)
        crest = os.path.join(os.path.dirname(__file__), "..", "assets", "crest.png")
        if os.path.exists(crest):  # the Vidyanexa crest, small, beside the footer line
            canvas.drawImage(crest, 16 * mm, 6.4 * mm, width=3.4 * mm, height=3.8 * mm, mask="auto")
        canvas.drawString(21 * mm, 8 * mm, f"Generated by Vidyanexa on {datetime.now():%d %b %Y, %I:%M %p}")
        canvas.drawRightString(A4[0] - 16 * mm, 8 * mm, f"Page {d.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()


WIDTH = A4[0] - 32 * mm

METHODS = {"cash": "Cash", "upi": "UPI", "cheque": "Cheque", "card": "Card", "bank_transfer": "Bank transfer", "online": "Online"}


def fee_receipt(r: Receipt) -> bytes:
    p, inv = r.payment, r.invoice
    story = _header(r.school_name, r.school_address, r.school_phone)
    story += [Paragraph("Fee receipt", H2),
              _facts([("Receipt no.", p.receipt_no), ("Date", f"{p.paid_at:%d %b %Y, %I:%M %p}"),
                      ("Student", inv.student_name), ("Admission no.", inv.admission_no),
                      ("Class", inv.class_section), ("Term", f"{inv.term} ({inv.academic_year})"),
                      ("Paid by", METHODS.get(p.method, p.method) + (f" · ref {p.reference}" if p.reference else "")),
                      ("Received by", p.collected_by or "—")], WIDTH),
              Spacer(1, 10)]
    rows = [["Fee", "Amount"]] + [[i.name, money(i.amount)] for i in inv.items]
    rows += [["Total", money(inv.total)]]
    if inv.discount:
        rows += [[f"Discount{f' ({inv.discount_reason})' if inv.discount_reason else ''}", f"- {money(inv.discount)}"]]
    t = _grid(rows, [WIDTH * 0.7, WIDTH * 0.3])
    t.setStyle(TableStyle([("ALIGN", (1, 0), (1, -1), "RIGHT"), ("FONT", (0, len(inv.items) + 1), (-1, len(inv.items) + 1), "Helvetica-Bold", 9.5)]))
    story += [t, Spacer(1, 10)]
    summary = _grid([["Amount received", money(p.amount)], ["Total paid so far", money(inv.paid)], ["Balance due", money(r.balance_after)]],
                    [WIDTH * 0.7, WIDTH * 0.3], header=False)
    summary.setStyle(TableStyle([("ALIGN", (1, 0), (1, -1), "RIGHT"), ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 11),
                                 ("TEXTCOLOR", (0, 0), (-1, 0), BRAND), ("BACKGROUND", (0, 0), (-1, 0), SOFT)]))
    story += [summary, Spacer(1, 18),
              Paragraph("This is a computer-generated receipt and needs no signature.", SMALL)]
    return build(story, f"Receipt {p.receipt_no}")


def _num(v) -> str:
    if v is None:
        return "—"
    v = Decimal(v)
    return f"{v:.0f}" if v == v.to_integral() else f"{v:.2f}".rstrip("0")


def report_card(rc: ReportCard) -> bytes:
    res = rc.result
    story = _header(rc.school_name, rc.school_address)
    story += [Paragraph(f"Report card · {_esc(rc.exam_name)} · {_esc(rc.academic_year)}", H2),
              _facts([("Student", rc.student_name), ("Admission no.", rc.admission_no),
                      ("Class", rc.class_section), ("Roll no.", str(rc.roll_no or "—")),
                      ("Date of birth", f"{rc.date_of_birth:%d %b %Y}"), ("Class teacher", rc.class_teacher or "—")], WIDTH),
              Spacer(1, 10)]
    rows = [["Subject", "Max", "Pass", "Marks", "Grade", "Result"]]
    for s in res.subjects:
        rows.append([s.subject_name, _num(s.max_marks), _num(s.pass_marks), "Absent" if s.absent else _num(s.marks),
                     s.grade or "—", "—" if s.passed is None else ("Pass" if s.passed else "Fail")])
    rows.append(["Total", _num(res.max_total), "", _num(res.total), res.grade or "—", "Pass" if res.passed else "Fail"])
    w = WIDTH
    t = _grid(rows, [w * 0.36, w * 0.11, w * 0.11, w * 0.14, w * 0.12, w * 0.16])
    style = [("ALIGN", (1, 0), (-1, -1), "CENTER"), ("FONT", (0, -1), (-1, -1), "Helvetica-Bold", 9.5)]
    for i, s in enumerate(res.subjects, start=1):
        if s.passed is False:
            style.append(("TEXTCOLOR", (5, i), (5, i), colors.HexColor("#dc2626")))
    t.setStyle(TableStyle(style))
    story += [t, Spacer(1, 10)]
    story.append(_facts([
        ("Percentage", f"{res.percent:.1f}%" if res.percent is not None else "—"), ("Overall grade", res.grade or "—"),
        ("Rank in class", f"{res.rank} of {rc.class_size}" if res.rank else "—"),
        ("Attendance this year", f"{rc.attendance_percent:.1f}%" if rc.attendance_percent is not None else "—"),
    ], WIDTH))
    if rc.co_scholastic:
        story += [Spacer(1, 10), Paragraph("<b>Co-scholastic areas</b>", BODY), Spacer(1, 4)]
        co = _grid([["Area", "Grade"]] + [[c["area"], c["grade"]] for c in rc.co_scholastic], [WIDTH * 0.75, WIDTH * 0.25])
        co.setStyle(TableStyle([("ALIGN", (1, 0), (1, -1), "CENTER")]))
        story += [co, Paragraph("A: outstanding · B: very good · C: fair", SMALL)]
    story += [Spacer(1, 10), Paragraph("<b>Class teacher's remark</b>", BODY), Paragraph(_esc(res.remark or "—"), BODY), Spacer(1, 36)]
    sig = _signatures(["Class teacher", "Principal", "Parent"])
    story += [sig, Spacer(1, 10), Paragraph("Grades: A1 91–100, A2 81–90, B1 71–80, B2 61–70, C1 51–60, C2 41–50, D 33–40, E below 33.", SMALL)]
    return build(story, f"Report card {rc.student_name}")


def pdf_response(data: bytes, filename: str, download: bool = False):
    from fastapi import Response
    return Response(data, media_type="application/pdf", headers={
        "Content-Disposition": f'{"attachment" if download else "inline"}; filename="{filename}"', "Cache-Control": "private, no-store"})


def today_str() -> str:
    return f"{date.today():%d %b %Y}"


# ---- certificates -----------------------------------------------------------------------------

@dataclass
class CertificateData:
    title: str
    kind: str
    serial_no: str
    issued_on: date
    school_name: str
    school_address: str | None
    school_phone: str | None
    student_name: str
    gender: str
    date_of_birth: date
    admission_no: str
    admission_date: date
    class_section: str
    parents: dict = field(default_factory=dict)
    details: dict = field(default_factory=dict)
    cancelled: bool = False


CERT_BODY = ParagraphStyle("cert", parent=BODY, fontSize=12, leading=20, alignment=4)  # justified


def _d(v) -> str:
    if not v:
        return "—"
    if isinstance(v, str):
        v = date.fromisoformat(v)
    return f"{v:%d %B %Y}"


def certificate(c: CertificateData) -> bytes:
    he, his = ("He", "his") if c.gender == "male" else ("She", "her") if c.gender == "female" else ("They", "their")
    child = "son" if c.gender == "male" else "daughter" if c.gender == "female" else "ward"
    parent = c.parents.get("father") or c.parents.get("mother") or c.parents.get("guardian")
    of = f"{child} of <b>{_esc(parent)}</b>, " if parent else ""
    d = c.details
    story = []
    if c.cancelled:
        story.append(Paragraph("<font color='#dc2626'><b>CANCELLED — NOT VALID</b></font>", H2))
    story += _header(c.school_name, c.school_address, c.school_phone)
    story += [Spacer(1, 6), Paragraph(c.title.upper(), ParagraphStyle("ct", parent=H2, fontSize=16, textColor=BRAND, spaceAfter=2)),
              Paragraph(f"No. {_esc(c.serial_no)} &nbsp;&nbsp;·&nbsp;&nbsp; Date: {_d(c.issued_on)}", SUB), Spacer(1, 16)]
    who = (f"This is to certify that <b>{_esc(c.student_name)}</b>, {of}admission number <b>{_esc(c.admission_no)}</b>, "
           f"date of birth <b>{_d(c.date_of_birth)}</b>")
    if c.kind == "bonafide":
        story.append(Paragraph(f"{who}, is a bonafide student of this school, studying in <b>{_esc(c.class_section)}</b> "
                               f"in the current academic session. {he} has been on our rolls since {_d(c.admission_date)}.", CERT_BODY))
        story += [Spacer(1, 10), Paragraph(f"This certificate is issued on request for the purpose of <b>{_esc(d.get('purpose'))}</b>.",
                                           CERT_BODY)]
    elif c.kind == "character":
        story.append(Paragraph(f"{who}, has been a student of this school since {_d(c.admission_date)} and is at present in "
                               f"<b>{_esc(c.class_section)}</b>.", CERT_BODY))
        story += [Spacer(1, 10), Paragraph(f"To the best of our knowledge, {his} conduct and character have been "
                                           f"<b>{_esc(d.get('conduct') or 'good')}</b>. We wish {'them' if his == 'their' else his} "
                                           f"every success.", CERT_BODY)]
    else:
        story += [Paragraph(f"{who}, was a student of this school.", CERT_BODY), Spacer(1, 10)]
        rows = [
            ["Name of the student", c.student_name], ["Father's name", c.parents.get("father") or "—"],
            ["Mother's name", c.parents.get("mother") or "—"], ["Date of birth", _d(c.date_of_birth)],
            ["Admission number", c.admission_no], ["Date of admission", _d(c.admission_date)],
            ["Class at the time of leaving", d.get("last_class") or c.class_section],
            ["Promoted to the next class", {"yes": "Yes", "no": "No", "na": "Not applicable"}.get(d.get("promoted"), "—")],
            ["Fees paid up to", d.get("fees_paid_upto") or "—"], ["Date of leaving", _d(d.get("leaving_date"))],
            ["Reason for leaving", d.get("reason") or "—"], ["General conduct", d.get("conduct") or "Good"],
        ]
        story.append(_grid([[Paragraph(f"<font color='#64748b'>{i + 1}. {_esc(k)}</font>", BODY), Paragraph(f"<b>{_esc(v)}</b>", BODY)]
                            for i, (k, v) in enumerate(rows)], [WIDTH * 0.45, WIDTH * 0.55], header=False))
    if d.get("remarks"):
        story += [Spacer(1, 10), Paragraph(f"<b>Remarks:</b> {_esc(d['remarks'])}", BODY)]
    story += [Spacer(1, 60)]
    sig = _signatures(["Prepared by", "Checked by", "Principal"])
    story += [sig, Spacer(1, 6), Paragraph("School seal", ParagraphStyle("seal", parent=SMALL, alignment=TA_RIGHT))]
    return build(story, f"{c.title} {c.serial_no}")


# ---- ID cards ---------------------------------------------------------------------------------

@dataclass
class IdCard:
    name: str
    class_section: str
    admission_no: str
    date_of_birth: date
    blood_group: str | None
    parent: str | None
    phone: str | None
    address: str | None
    photo: bytes | None = None


def _qr(text: str) -> ImageReader:
    import qrcode
    img = qrcode.make(text, box_size=4, border=1)
    buf = BytesIO()
    img.save(buf, format="PNG")
    buf.seek(0)
    return ImageReader(buf)


def id_cards(school_name: str, school_phone: str | None, valid_until: date, cards: list[IdCard]) -> bytes:
    """Credit-card sized cards (85.6 x 54 mm), ten to an A4 page."""
    buf = BytesIO()
    cv = pdfcanvas.Canvas(buf, pagesize=A4)
    cv.setTitle("Student ID cards")
    w, h = 85.6 * mm, 54 * mm
    gap_x, gap_y = 8 * mm, 4 * mm
    left = (A4[0] - 2 * w - gap_x) / 2
    top = A4[1] - 12 * mm
    for i, card in enumerate(cards):
        if i and i % 10 == 0:
            cv.showPage()
        col, row = i % 2, (i % 10) // 2
        x, y = left + col * (w + gap_x), top - (row + 1) * h - row * gap_y
        cv.setStrokeColor(LINE)
        cv.roundRect(x, y, w, h, 3 * mm, stroke=1, fill=0)
        cv.setFillColor(BRAND)  # band with the school name
        cv.roundRect(x, y + h - 11 * mm, w, 11 * mm, 3 * mm, stroke=0, fill=1)
        cv.rect(x, y + h - 11 * mm, w, 4 * mm, stroke=0, fill=1)
        cv.setFillColor(colors.white)
        cv.setFont("Helvetica-Bold", 9)
        cv.drawCentredString(x + w / 2, y + h - 5.3 * mm, school_name[:42])
        cv.setFont("Helvetica", 6)
        cv.drawCentredString(x + w / 2, y + h - 8.8 * mm, "STUDENT IDENTITY CARD" + (f"  ·  {school_phone}" if school_phone else ""))
        px, py, pw, ph = x + 3 * mm, y + 9 * mm, 20 * mm, 25 * mm
        cv.setFillColor(SOFT)
        cv.rect(px, py, pw, ph, stroke=0, fill=1)
        drawn = False
        if card.photo:
            try:
                cv.drawImage(ImageReader(BytesIO(card.photo)), px, py, pw, ph, preserveAspectRatio=True, anchor="c", mask="auto")
                drawn = True
            except Exception:
                drawn = False
        if not drawn:
            cv.setFillColor(MUTED)
            cv.setFont("Helvetica-Bold", 14)
            cv.drawCentredString(px + pw / 2, py + ph / 2 - 2 * mm, "".join(p[0] for p in card.name.split()[:2]).upper())
        tx = px + pw + 3 * mm
        cv.setFillColor(colors.black)
        cv.setFont("Helvetica-Bold", 9.5)
        cv.drawString(tx, y + h - 16 * mm, card.name[:30])
        cv.setFont("Helvetica", 7)
        lines = [("Class", card.class_section), ("Adm. no.", card.admission_no), ("DOB", f"{card.date_of_birth:%d %b %Y}"),
                 ("Blood", card.blood_group or "—"), ("Parent", card.parent or "—"), ("Phone", card.phone or "—")]
        for j, (k, v) in enumerate(lines):
            yy = y + h - 20.5 * mm - j * 3.6 * mm
            cv.setFillColor(MUTED)
            cv.drawString(tx, yy, k)
            cv.setFillColor(colors.black)
            cv.drawString(tx + 12 * mm, yy, str(v)[:26])
        cv.drawImage(_qr(card.admission_no), x + w - 15 * mm, y + 3 * mm, 12 * mm, 12 * mm)
        cv.setFont("Helvetica", 5.5)
        cv.setFillColor(MUTED)
        if card.address:
            cv.drawString(x + 3 * mm, y + 5.5 * mm, card.address[:62])
        cv.drawString(x + 3 * mm, y + 2.5 * mm, f"Valid until {valid_until:%d %b %Y}")
    cv.showPage()
    cv.save()
    return buf.getvalue()


# ---- payslip ----------------------------------------------------------------------------------

def payslip(*, school_name: str, school_address: str | None, month_label: str, name: str, employee_id: str | None, designation: str | None,
            department: str | None, pan: str | None, uan: str | None, bank: str | None, account: str | None, days_in_month: int,
            paid_days, lop_days, earnings: dict, deductions: dict, gross, total_deductions, net) -> bytes:
    story = _header(school_name, school_address)
    story += [Paragraph(f"Payslip · {_esc(month_label)}", H2),
              _facts([("Name", name), ("Employee ID", employee_id or "—"), ("Designation", designation or "—"), ("Department", department or "—"),
                      ("PAN", pan or "—"), ("UAN", uan or "—"), ("Bank account", f"{bank or ''} {('xxxx' + account[-4:]) if account else '—'}".strip()),
                      ("Days paid", f"{_num(paid_days)} of {days_in_month}" + (f" ({_num(lop_days)} without pay)" if Decimal(str(lop_days)) else ""))], WIDTH),
              Spacer(1, 10)]
    e_rows, d_rows = list(earnings.items()), list(deductions.items())
    n = max(len(e_rows), len(d_rows), 1)
    rows = [["Earnings", "Amount", "Deductions", "Amount"]]
    for i in range(n):
        e = e_rows[i] if i < len(e_rows) else ("", None)
        d = d_rows[i] if i < len(d_rows) else ("", None)
        rows.append([e[0], money(e[1]) if e[1] is not None else "", d[0], money(d[1]) if d[1] is not None else ""])
    rows.append(["Gross earnings", money(gross), "Total deductions", money(total_deductions)])
    t = _grid(rows, [WIDTH * 0.3, WIDTH * 0.2, WIDTH * 0.3, WIDTH * 0.2])
    t.setStyle(TableStyle([("ALIGN", (1, 0), (1, -1), "RIGHT"), ("ALIGN", (3, 0), (3, -1), "RIGHT"),
                           ("FONT", (0, -1), (-1, -1), "Helvetica-Bold", 9.5)]))
    story += [t, Spacer(1, 10)]
    tot = _grid([["Net pay", money(net)]], [WIDTH * 0.7, WIDTH * 0.3], header=False)
    tot.setStyle(TableStyle([("ALIGN", (1, 0), (1, 0), "RIGHT"), ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 12), ("TEXTCOLOR", (0, 0), (-1, 0), BRAND),
                             ("BACKGROUND", (0, 0), (-1, 0), SOFT)]))
    story += [tot, Spacer(1, 14), Paragraph("This is a computer-generated payslip and needs no signature.", SMALL)]
    return build(story, f"Payslip {name} {month_label}")
